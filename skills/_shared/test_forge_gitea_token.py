def test_no_yaml_library_is_imported_by_the_backend():
    """Token discovery must stay stdlib-only — a consumer repo has no PyYAML."""
    source = (Path(__file__).resolve().parent / "forge_gitea.py").read_text(encoding="utf-8")
    imported = [line.split() for line in source.splitlines()
                if line.startswith(("import ", "from "))]
    assert not [names for names in imported
                if any(part.split(".")[0].endswith("yaml") for part in names)]


def test_setup_line_names_both_ways_to_supply_a_token():
    line = forge_gitea.setup_line("https://gitea.lan")
    assert "export GITEA_TOKEN=" in line
    assert "tea login add --url https://gitea.lan" in line
    assert "\n" not in line


def test_resolve_uses_read_tea_logins_when_the_seam_is_absent(monkeypatch, tmp_path):
    """Differential-ish: resolve()'s default `tea_logins` IS `read_tea_logins()`."""
    import forge

    cfg = tea(tmp_path, TEA_CONFIG)
    monkeypatch.setattr(forge_gitea, "DEFAULT_TEA_CONFIG", cfg)

    def runner(argv, **kwargs):
        return FakeCompleted(0, "ssh://git@gitea.lan:2222/home/lab.git\n")

    class FakeCompleted:
        def __init__(self, returncode: int, stdout: str = "") -> None:
            self.returncode = returncode
            self.stdout = stdout
            self.stderr = ""

    class Resp:
        def read(self) -> bytes:
            return b'{"version": "1.22.1"}'

        def __enter__(self):
            return self

        def __exit__(self, *exc) -> bool:
            return False

    urls = []

    def open_(request, timeout=None, context=None):
        urls.append(request.full_url)
        return Resp()

    info = forge.resolve("/fixture/repo", config={}, runner=runner, urlopen=open_)
    assert info.web_base == "https://gitea.lan"  # the tea login url won over :2222
    assert urls == ["https://gitea.lan/api/v1/version"]
