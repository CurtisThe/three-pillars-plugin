"""test_commit_guard_status.py — `status`/`refusal_cause`/`refresh`/`decline` (Task 5.4).

`status(repo) -> dict` (part E) tells an effective install from a stale,
missing or disabled one; `refusal_cause(repo)` is the per-clone predicate;
`refresh` rewrites a `v<N-1>` block; `decline` writes only the per-clone
marker. Refusals write no hook, touch no committed config, return two
snippets and record the cause per clone. House rules: real tmp_path repos,
GIT_* scrubbed, HOME isolated, `{"schema_version": 1}` committed first; the
global `core.hooksPath` case points `GIT_CONFIG_GLOBAL` at a temp file.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

# Import by bare name (the shipped-collect guard runs pytest from inside
# skills/_shared, where the `skills` namespace is not on sys.path).
_SHARED_DIR = Path(__file__).resolve().parent
if str(_SHARED_DIR) not in sys.path:
    sys.path.insert(0, str(_SHARED_DIR))

import commit_guard  # noqa: E402

SCRIPT = _SHARED_DIR / "commit_guard.py"
CLEAN_ENV = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
CLEAN_ENV.update({
    "GIT_AUTHOR_NAME": "fixture", "GIT_AUTHOR_EMAIL": "fixture@test",
    "GIT_COMMITTER_NAME": "fixture", "GIT_COMMITTER_EMAIL": "fixture@test",
})


@pytest.fixture(autouse=True)
def _isolated_env(tmp_path, monkeypatch):
    """Scrub inherited GIT_* vars and isolate HOME (the guard runs git with the
    ambient os.environ)."""
    for key in [k for k in os.environ if k.startswith("GIT_")]:
        monkeypatch.delenv(key, raising=False)
    (tmp_path / "home").mkdir()
    monkeypatch.setenv("HOME", str(tmp_path / "home"))


def _git(args: list[str], cwd: Path) -> str:
    proc = subprocess.run(["git", *args], cwd=str(cwd), check=True, env=CLEAN_ENV,
                          capture_output=True, text=True, stdin=subprocess.DEVNULL)
    return proc.stdout.strip()


def _repo(tmp_path: Path) -> Path:
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(["init", "-q", "-b", "main"], repo)
    (repo / "README.md").write_text("init\n", encoding="utf-8")
    _git(["add", "README.md"], repo)
    _git(["commit", "-q", "-m", "init"], repo)
    (repo / ".three-pillars").mkdir(parents=True)
    (repo / ".three-pillars" / "config.json").write_text('{"schema_version": 1}\n', encoding="utf-8")
    _git(["add", ".three-pillars/config.json"], repo)
    _git(["commit", "-q", "-m", "seed config"], repo)
    return repo


def _hooks_dir(repo: Path) -> Path:
    return Path(_git(["rev-parse", "--path-format=absolute",
                      "--git-path", "hooks"], repo))


def _common_dir(repo: Path) -> Path:
    return Path(_git(["rev-parse", "--path-format=absolute",
                      "--git-common-dir"], repo))


def _write(path: Path, text: str, mode: int) -> None:
    path.write_text(text, encoding="utf-8")
    path.chmod(mode)


def _manual(repo: Path) -> Path:
    return _common_dir(repo) / "three-pillars" / "commit-guard-manual"  # per-clone refusal marker


GENERATED = ("#!/bin/sh\n# File generated by pre-commit\n"
             "# ID: 9d8a5241f041c41d6b3a8e9f5a1b2c3d4e5f6a7b8c9d0e1f2a3b4c5d6e7f8a9b\n"
             'exec python3 -mpre_commit.hook_impl --hook-dir "/srv/pre-commit" '
             '--hook-type pre-commit "$@"\n')
FOREIGN = "#!/bin/sh\necho foreign-hook-ran\n"


def _snippets(excinfo) -> list[str]:
    snips = excinfo.value.snippets
    assert len(snips) == 2, "apply must return two manual snippets"
    for snip in snips:
        assert "commit-guard BEGIN v" in snip
        assert "_tp_commit_guard" in snip
    return snips


def test_status_shape_and_each_target(tmp_path):
    repo = _repo(tmp_path)
    st = commit_guard.status(str(repo))
    assert set(st) == {"hooks_dir", "hooks_dir_ok", "hooks", "tp_root",
                       "local_decline", "manual", "stale", "effective"}
    assert st["hooks_dir_ok"] is True and st["effective"] is False
    assert st["tp_root"] is None and st["local_decline"] is False
    assert st["manual"] is None and st["stale"] is False
    for name in ("pre-commit", "commit-msg"):
        assert set(st["hooks"][name]) == {
            "target", "manager", "sentinel", "version", "stale", "effective"}
        h = st["hooks"][name]
        assert h["target"] is None and h["manager"] is None
        assert h["sentinel"] is False and h["version"] is None
        assert h["stale"] is False and h["effective"] is False
    hooks = _hooks_dir(repo)
    for name in ("pre-commit", "commit-msg"):
        _write(hooks / name, FOREIGN, 0o755)
    commit_guard.apply(str(repo))
    st = commit_guard.status(str(repo))
    assert st["effective"] is True and st["stale"] is False
    assert st["tp_root"] is not None
    for name in ("pre-commit", "commit-msg"):
        h = st["hooks"][name]
        assert h["target"] == "hook" and h["manager"] == "foreign"
        assert h["sentinel"] and h["version"] == commit_guard.BODY_VERSION
        assert h["stale"] is False and h["effective"] is True
    _write(hooks / "pre-commit", GENERATED, 0o755)  # the target becomes <hook>.legacy
    commit_guard.apply(str(repo))
    h = commit_guard.status(str(repo))["hooks"]["pre-commit"]
    assert h["target"] == "legacy" and h["manager"] == "pre-commit"
    assert h["sentinel"] and h["effective"]


def test_in_tree_hooks_path_refused_snippets_marker_no_config(tmp_path):
    repo = _repo(tmp_path)
    (repo / "scripts" / "githooks").mkdir(parents=True)
    _git(["config", "core.hooksPath", "scripts/githooks"], repo)
    before = (repo / ".three-pillars" / "config.json").read_bytes()
    with pytest.raises(commit_guard.Refused) as excinfo:
        commit_guard.apply(str(repo))
    _snippets(excinfo)
    cause = excinfo.value.cause
    assert "common dir" in cause
    hooks = _hooks_dir(repo)
    assert not (hooks / "pre-commit").exists() and not (hooks / "commit-msg").exists()
    assert (repo / ".three-pillars" / "config.json").read_bytes() == before
    marker = _manual(repo)
    assert marker.exists() and marker.read_text(encoding="utf-8") == cause
    st = commit_guard.status(str(repo))
    assert st["hooks_dir_ok"] is False and st["effective"] is False
    assert st["manual"] == cause


def test_global_hooks_path_refused_then_removed(tmp_path, monkeypatch):
    repo = _repo(tmp_path)
    outside = tmp_path / "githooks"
    outside.mkdir()
    gcfg = tmp_path / "gitconfig"
    gcfg.write_text(f"[core]\n\thooksPath = {outside}\n", encoding="utf-8")
    monkeypatch.setenv("GIT_CONFIG_GLOBAL", str(gcfg))
    before = (repo / ".three-pillars" / "config.json").read_bytes()
    with pytest.raises(commit_guard.Refused) as excinfo:
        commit_guard.apply(str(repo))
    _snippets(excinfo)
    assert (repo / ".three-pillars" / "config.json").read_bytes() == before
    assert _manual(repo).exists()
    st = commit_guard.status(str(repo))
    assert st["hooks_dir_ok"] is False and st["effective"] is False
    assert st["manual"] is not None
    assert commit_guard.refusal_cause(str(repo)) is not None
    gcfg.write_text("[core]\n", encoding="utf-8")  # the global hooksPath is removed
    assert commit_guard.refusal_cause(str(repo)) is None


def test_python_shebang_refused_two_snippets_marker(tmp_path):
    repo = _repo(tmp_path)
    hooks = _hooks_dir(repo)
    _write(hooks / "pre-commit", "#!/usr/bin/env python3\nprint('x')\n", 0o755)
    before = (repo / ".three-pillars" / "config.json").read_bytes()
    with pytest.raises(commit_guard.Refused) as excinfo:
        commit_guard.apply(str(repo))
    _snippets(excinfo)
    assert "shebang" in excinfo.value.cause
    assert (repo / ".three-pillars" / "config.json").read_bytes() == before
    assert not (hooks / "commit-msg").exists()
    assert _manual(repo).exists()
    st = commit_guard.status(str(repo))
    assert st["hooks"]["pre-commit"]["effective"] is False
    assert st["manual"] is not None


def test_second_clone_without_marker_still_offered(tmp_path):
    repo = _repo(tmp_path)
    (repo / "scripts" / "githooks").mkdir(parents=True)
    _git(["config", "core.hooksPath", "scripts/githooks"], repo)
    with pytest.raises(commit_guard.Refused):
        commit_guard.apply(str(repo))
    assert _manual(repo).exists()
    # a teammate's clean clone has no per-clone marker and no in-tree hooksPath
    clone = tmp_path / "clone"
    _git(["clone", "-q", str(repo), str(clone)], repo)
    assert not (_common_dir(Path(clone)) / "three-pillars" / "commit-guard-manual").exists()
    st = commit_guard.status(str(clone))
    assert st["manual"] is None and st["local_decline"] is False
    assert commit_guard.refusal_cause(str(clone)) is None
    assert st["hooks_dir_ok"] is True, "the clone is still offered the install"


def test_fresh_clone_with_applied_at_not_effective_brief_exit_3(tmp_path):
    from skills._shared.repo_config_load import update_config

    repo = _repo(tmp_path)
    # A teammate applied and committed the config: HEAD carries applied_at.
    # (Committed before the hooks are installed, so this fixture commit is
    # not run through the guard — `run` lands in Task 5.5.)
    update_config(repo, "commit_guard.applied_at", "2026-09-26T00:00:00Z")
    _git(["add", ".three-pillars/config.json"], repo)
    _git(["commit", "-q", "-m", "record applied_at"], repo)
    assert json.loads((repo / ".three-pillars" / "config.json").read_text(encoding="utf-8"))["commit_guard"]["applied_at"]
    commit_guard.apply(str(repo))  # this clone has the guard installed
    clone = tmp_path / "clone"
    _git(["clone", "-q", str(repo), str(clone)], repo)
    st = commit_guard.status(str(clone))
    assert st["effective"] is False, "a fresh clone has no .git/hooks"
    proc = subprocess.run([sys.executable, str(SCRIPT), "status", "--brief",
                           "--repo", str(clone)],
                          capture_output=True, text=True, env=CLEAN_ENV)
    assert proc.returncode == 3, proc.stdout + proc.stderr
    ok = subprocess.run([sys.executable, str(SCRIPT), "status", "--brief",
                         "--repo", str(repo)],
                        capture_output=True, text=True, env=CLEAN_ENV)
    assert ok.returncode == 0, ok.stdout + ok.stderr


def test_chmod_x_on_installed_hook_not_effective(tmp_path):
    repo = _repo(tmp_path)
    commit_guard.apply(str(repo))
    assert commit_guard.status(str(repo))["effective"] is True
    hook = _hooks_dir(repo) / "pre-commit"
    hook.chmod(hook.stat().st_mode & ~0o111)
    st = commit_guard.status(str(repo))
    assert st["hooks"]["pre-commit"]["sentinel"] is True
    assert st["hooks"]["pre-commit"]["effective"] is False
    assert st["hooks"]["commit-msg"]["effective"] is True
    assert st["effective"] is False


def test_global_hooks_path_after_install_top_level_not_effective(tmp_path, monkeypatch):
    repo = _repo(tmp_path)
    commit_guard.apply(str(repo))
    assert commit_guard.status(str(repo))["effective"] is True
    outside = tmp_path / "githooks"
    outside.mkdir()
    gcfg = tmp_path / "gitconfig"
    gcfg.write_text(f"[core]\n\thooksPath = {outside}\n", encoding="utf-8")
    monkeypatch.setenv("GIT_CONFIG_GLOBAL", str(gcfg))
    st = commit_guard.status(str(repo))
    assert st["hooks_dir_ok"] is False
    assert st["effective"] is False, "git now ignores .git/hooks"


def test_stale_block_reports_stale_and_refresh_clears_it(tmp_path):
    repo = _repo(tmp_path)
    hooks = _hooks_dir(repo)
    old = ("#!/bin/sh\n# three-pillars: commit-guard BEGIN v0\n"
           "# stale guard body\n"
           '_tp_commit_guard pre-commit "$@" || exit $?\n'
           "# three-pillars: commit-guard END\necho foreign\n")
    for name in ("pre-commit", "commit-msg"):
        _write(hooks / name, old.replace("pre-commit", name), 0o755)
    st = commit_guard.status(str(repo))
    assert st["stale"] is True
    for name in ("pre-commit", "commit-msg"):
        h = st["hooks"][name]
        assert h["version"] == 0 and h["stale"] is True
        assert h["effective"] is True, "a stale block still runs"
    before = (repo / ".three-pillars" / "config.json").read_bytes()
    commit_guard.refresh(str(repo))
    assert (repo / ".three-pillars" / "config.json").read_bytes() == before
    st = commit_guard.status(str(repo))
    assert st["stale"] is False
    for name in ("pre-commit", "commit-msg"):
        h = st["hooks"][name]
        assert h["version"] == commit_guard.BODY_VERSION
        assert h["stale"] is False and h["effective"] is True
        text = (hooks / name).read_text(encoding="utf-8")
        assert "echo foreign" in text and "stale guard body" not in text


def test_decline_marker_reports_local_decline(tmp_path):
    repo = _repo(tmp_path)
    before = (repo / ".three-pillars" / "config.json").read_bytes()
    commit_guard.decline(str(repo))
    assert (_common_dir(repo) / "three-pillars" / "commit-guard-declined").exists()
    assert (repo / ".three-pillars" / "config.json").read_bytes() == before
    st = commit_guard.status(str(repo))
    assert st["local_decline"] is True
    assert st["manual"] is None
