"""test_commit_guard_legacy.py — `commit_guard` and the pre-commit framework (Task 5.4).

Install rule 1 (part E §Install): when the hook is a pre-commit-framework script
(it contains `File generated by pre-commit` and `hook-impl`), the guard block
lands in `<hook>.legacy`, not the hook — pre-commit's `install` overwrites its
own script whole (`is_our_script`), so a block inside it would vanish at the
next `pre-commit install`, while `hook_impl` runs an executable `<hook>.legacy`
first and it survives a plain re-install. Three sub-cases refuse instead: a
`.legacy` that exists but is not executable, a generated script without
`--hook-dir`, and a generated script that is not executable.

House rules: real tmp_path git repos, GIT_* env scrubbed, HOME isolated,
`{"schema_version": 1}` committed first. The generated script is a copied
minimal representative (not the pre-commit package). Stdlib + pytest only.
"""
from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

import pytest

# Import by bare name (the shipped-collect guard runs pytest from inside
# skills/_shared, where the `skills` namespace is not on sys.path).
_SHARED_DIR = Path(__file__).resolve().parent
if str(_SHARED_DIR) not in sys.path:
    sys.path.insert(0, str(_SHARED_DIR))

import commit_guard  # noqa: E402

CLEAN_ENV = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
CLEAN_ENV.update({
    "GIT_AUTHOR_NAME": "fixture", "GIT_AUTHOR_EMAIL": "fixture@test",
    "GIT_COMMITTER_NAME": "fixture", "GIT_COMMITTER_EMAIL": "fixture@test",
})


@pytest.fixture(autouse=True)
def _isolated_env(tmp_path, monkeypatch):
    """Scrub inherited GIT_* vars and isolate HOME: the guard runs git through
    subprocess with the ambient os.environ."""
    for key in [k for k in os.environ if k.startswith("GIT_")]:
        monkeypatch.delenv(key, raising=False)
    home = tmp_path / "home"
    home.mkdir()
    monkeypatch.setenv("HOME", str(home))


def _git(args: list[str], cwd: Path) -> None:
    subprocess.run(["git", *args], cwd=str(cwd), check=True, env=CLEAN_ENV,
                   capture_output=True, text=True, stdin=subprocess.DEVNULL)


def _repo(tmp_path: Path) -> Path:
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(["init", "-q", "-b", "main"], repo)
    (repo / "README.md").write_text("init\n", encoding="utf-8")
    _git(["add", "README.md"], repo)
    _git(["commit", "-q", "-m", "init"], repo)
    (repo / ".three-pillars").mkdir(parents=True)
    (repo / ".three-pillars" / "config.json").write_text(
        '{"schema_version": 1}\n', encoding="utf-8")
    _git(["add", ".three-pillars/config.json"], repo)
    _git(["commit", "-q", "-m", "seed config"], repo)
    return repo


def _hooks_dir(repo: Path) -> Path:
    raw = subprocess.run(["git", "-C", str(repo), "rev-parse",
                          "--path-format=absolute", "--git-path", "hooks"],
                         check=True, capture_output=True, text=True,
                         env=CLEAN_ENV).stdout.strip()
    return Path(raw)


def _common_dir(repo: Path) -> Path:
    raw = subprocess.run(["git", "-C", str(repo), "rev-parse",
                          "--path-format=absolute", "--git-common-dir"],
                         check=True, capture_output=True, text=True,
                         env=CLEAN_ENV).stdout.strip()
    return Path(raw)


def _config(repo: Path) -> dict:
    import json
    return json.loads((repo / ".three-pillars" / "config.json").read_text(encoding="utf-8"))


# A minimal representative of a pre-commit generated script: it carries the
# two markers the guard looks for, and passes `--hook-dir` to `hook_impl`.
GENERATED = (
    "#!/bin/sh\n"
    "# File generated by pre-commit\n"
    "# ID: 9d8a5241f041c41d6b3a8e9f5a1b2c3d4e5f6a7b8c9d0e1f2a3b4c5d6e7f8a9b\n"
    "# PRE-COMMIT DEFAULT CONTENT\n"
    "# DO NOT EDIT THIS FILE - pre-commit rewrites it on `pre-commit install`\n"
    'exec python3 -mpre_commit.hook_impl --hook-dir "/srv/pre-commit" '
    '--config-file "/srv/pre-commit/.pre-commit-config.yaml" '
    '--hook-type pre-commit "$@"\n'
)

# Same, but the generated script passes no `--hook-dir` (the git 2.54+
# config-hook path where `hook_impl` never runs a `.legacy`).
GENERATED_NO_HOOKDIR = (
    "#!/bin/sh\n"
    "# File generated by pre-commit\n"
    "# ID: 9d8a5241f041c41d6b3a8e9f5a1b2c3d4e5f6a7b8c9d0e1f2a3b4c5d6e7f8a9b\n"
    'exec python3 -mpre_commit.hook_impl '
    '--config-file "/srv/pre-commit/.pre-commit-config.yaml" '
    '--hook-type pre-commit "$@"\n'
)

FOREIGN = "#!/bin/sh\necho foreign-hook-ran\n"


def _write(path: Path, text: str, mode: int) -> None:
    path.write_text(text, encoding="utf-8")
    path.chmod(mode)


def test_block_lands_in_legacy_not_the_hook(tmp_path):
    repo = _repo(tmp_path)
    hooks = _hooks_dir(repo)
    _write(hooks / "pre-commit", GENERATED, 0o755)   # a pre-commit script
    _write(hooks / "commit-msg", FOREIGN, 0o755)     # a foreign hook
    commit_guard.apply(str(repo))
    # pre-commit: the block went into pre-commit.legacy; the hook is untouched
    legacy = hooks / "pre-commit.legacy"
    assert legacy.exists() and os.access(str(legacy), os.X_OK)
    assert f"commit-guard BEGIN v{commit_guard.BODY_VERSION}" in legacy.read_text(encoding="utf-8")
    assert (hooks / "pre-commit").read_text(encoding="utf-8") == GENERATED
    # commit-msg: the foreign hook got the block after its shebang; no .legacy
    cm = hooks / "commit-msg"
    text = cm.read_text(encoding="utf-8")
    assert text.startswith("#!/bin/sh\n" + f"# three-pillars: commit-guard BEGIN v{commit_guard.BODY_VERSION}\n")
    assert "echo foreign-hook-ran" in text
    assert not (hooks / "commit-msg.legacy").exists()


def test_simulated_precommit_install_keeps_status_effective(tmp_path):
    repo = _repo(tmp_path)
    hooks = _hooks_dir(repo)
    _write(hooks / "pre-commit", GENERATED, 0o755)
    _write(hooks / "commit-msg", FOREIGN, 0o755)
    commit_guard.apply(str(repo))
    assert commit_guard.status(str(repo))["hooks"]["pre-commit"]["effective"]
    # pre-commit install rewrites its own script whole; the .legacy survives
    _write(hooks / "pre-commit", GENERATED, 0o755)
    st = commit_guard.status(str(repo))["hooks"]["pre-commit"]
    assert st["target"] == "legacy" and st["manager"] == "pre-commit"
    assert st["sentinel"] and st["effective"]


def test_install_force_deletes_legacy_not_effective(tmp_path):
    repo = _repo(tmp_path)
    hooks = _hooks_dir(repo)
    _write(hooks / "pre-commit", GENERATED, 0o755)
    _write(hooks / "commit-msg", FOREIGN, 0o755)
    commit_guard.apply(str(repo))
    assert commit_guard.status(str(repo))["hooks"]["pre-commit"]["effective"]
    # pre-commit install -f deletes the .legacy
    (hooks / "pre-commit.legacy").unlink()
    st = commit_guard.status(str(repo))["hooks"]["pre-commit"]
    assert not st["sentinel"] and not st["effective"]
    assert commit_guard.status(str(repo))["effective"] is False


def test_non_executable_legacy_refused(tmp_path):
    repo = _repo(tmp_path)
    hooks = _hooks_dir(repo)
    _write(hooks / "pre-commit", GENERATED, 0o755)
    legacy = hooks / "pre-commit.legacy"
    _write(legacy, FOREIGN, 0o644)  # exists but not executable
    before = _config(repo)
    with pytest.raises(commit_guard.Refused):
        commit_guard.apply(str(repo))
    assert legacy.read_text(encoding="utf-8") == FOREIGN
    assert not (hooks / "commit-msg").exists(), "no hook may be written"
    assert _config(repo) == before, "the committed config is not touched"
    marker = _common_dir(repo) / "three-pillars" / "commit-guard-manual"
    assert marker.exists(), "the per-clone refusal marker is written"
    cause = marker.read_text(encoding="utf-8")
    assert "legacy" in cause and "not executable" in cause


def test_non_executable_generated_script_refused(tmp_path):
    repo = _repo(tmp_path)
    hooks = _hooks_dir(repo)
    _write(hooks / "pre-commit", GENERATED, 0o644)  # generated script not executable
    before = _config(repo)
    with pytest.raises(commit_guard.Refused):
        commit_guard.apply(str(repo))
    assert (hooks / "pre-commit").read_text(encoding="utf-8") == GENERATED
    assert (hooks / "pre-commit").stat().st_mode & 0o111 == 0
    assert not (hooks / "commit-msg").exists()
    assert _config(repo) == before


def test_generated_script_without_hook_dir_refused(tmp_path):
    repo = _repo(tmp_path)
    hooks = _hooks_dir(repo)
    _write(hooks / "pre-commit", GENERATED_NO_HOOKDIR, 0o755)
    before = _config(repo)
    with pytest.raises(commit_guard.Refused):
        commit_guard.apply(str(repo))
    assert (hooks / "pre-commit").read_text(encoding="utf-8") == GENERATED_NO_HOOKDIR
    assert not (hooks / "commit-msg").exists()
    assert _config(repo) == before


def test_non_shell_legacy_refused(tmp_path):
    """The `.legacy` target gets the same shebang rule as a plain hook."""
    repo = _repo(tmp_path)
    hooks = _hooks_dir(repo)
    _write(hooks / "pre-commit", GENERATED, 0o755)
    _write(hooks / "pre-commit.legacy", "#!/usr/bin/env python3\nprint('x')\n", 0o755)
    with pytest.raises(commit_guard.Refused) as excinfo:
        commit_guard.apply(str(repo))
    assert "shebang" in excinfo.value.cause
    assert "commit-guard" not in (hooks / "pre-commit.legacy").read_text(encoding="utf-8")


def test_refusal_is_all_or_nothing_and_snippets_are_whole_blocks(tmp_path):
    """A refused `commit-msg` leaves `pre-commit` unwritten; each snippet is
    the whole block (BEGIN..END), so a later `apply` finds it current."""
    repo = _repo(tmp_path)
    hooks = _hooks_dir(repo)
    _write(hooks / "commit-msg", "#!/usr/bin/env python3\nprint('x')\n", 0o755)
    with pytest.raises(commit_guard.Refused) as excinfo:
        commit_guard.apply(str(repo))
    assert not (hooks / "pre-commit").exists()
    for snip in excinfo.value.snippets:
        assert f"BEGIN v{commit_guard.BODY_VERSION}" in snip
        assert snip.rstrip().endswith("# three-pillars: commit-guard END")
