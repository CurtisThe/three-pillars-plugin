"""commit_guard_hooks.py — the per-hook install and status logic (Task 5.4).

The pure analysis split out of `commit_guard.py` by responsibility so the
entry point stays under the file-size cap: `_hooks_dir_ok` (the realpath
common-dir scope check, part E §Where it may install), `install_hook`
(insert the block into a hook or its `.legacy`, refusing the unsafe
sub-cases, part E §Install), `hook_status` (the per-hook H dict, part E
§status) and `hook_refusal_cause` (the per-hook cause, part E §Refusals).

Shared foundation (`BODY_VERSION`, `HOOK_NAMES`, `Refused`, the marker paths
and the block/snippet builders) is imported from `commit_guard_settings`;
this module imports neither `commit_guard` nor vice versa — no cycle.
"""
from __future__ import annotations

import os
from pathlib import Path

from commit_guard_settings import (
    _SENTINEL_BEGIN_RE, _SENTINEL_END, BODY_VERSION, HOOK_NAMES, Refused,
    _common_dir, _hooks_dir, block_lines, snippets_for)

_SHELL_NAMES = ("sh", "bash", "dash", "zsh")


def _shebang_is_posix_shell(line: str) -> bool:
    """No shebang or a POSIX-shell shebang (`sh`, `bash`, `dash`, `zsh`,
    directly or through `/usr/bin/env`): the block may run before the
    foreign lines and still let them run afterwards."""
    if not line.startswith("#!"):
        return True
    argv = line[2:].strip().split()
    if not argv:
        return False
    target = argv[1] if Path(argv[0]).name == "env" and len(argv) > 1 else argv[0]
    return Path(target).name in _SHELL_NAMES


def _find_sentinel(lines: list) -> tuple | None:
    """The `[begin, end, version]` span of an existing block in `lines`, or
    None. A BEGIN without an END degrades to a span to the end of the file
    (a broken block is replaced, never stacked)."""
    for i, line in enumerate(lines):
        match = _SENTINEL_BEGIN_RE.match(line)
        if not match:
            continue
        for j in range(i + 1, len(lines)):
            if lines[j].strip() == _SENTINEL_END:
                version = int(match.group(1)) if match.group(1) else None
                return i, j, version
        return i, len(lines) - 1, None  # BEGIN without END
    return None


def _is_generated(text: str) -> bool:
    """A pre-commit-framework script (part E §Install rule 1): it carries the
    `File generated by pre-commit` marker and references the `hook_impl`
    runner (recorded as `hook-impl`; the real script invokes
    `pre_commit.hook_impl`)."""
    return ("File generated by pre-commit" in text
            and ("hook-impl" in text or "hook_impl" in text))


def _has_hook_dir(text: str) -> bool:
    return "--hook-dir" in text


def _hooks_dir_ok(repo) -> tuple:
    """The git hooks dir (realpath) and whether it is under the common dir
    (realpath). Part E §Where it may install: a hooks dir outside the common
    dir (a tracked in-tree dir, or a repo/global `core.hooksPath` shared by
    every repo on the machine) is refused — a block there would print
    "plugin not found" on every commit elsewhere."""
    hooks_dir = _hooks_dir(repo)
    hooks_dir = hooks_dir.resolve() if hooks_dir else None
    common = _common_dir(repo)
    ok = bool(hooks_dir and common)
    if ok:
        common_r = common.resolve()
        ok = hooks_dir == common_r or common_r in hooks_dir.parents
    return hooks_dir, ok


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")


def _non_shell(path: Path) -> bool:
    first = _read(path).splitlines()[:1]
    return bool(first) and not _shebang_is_posix_shell(first[0])


def _link_out_cause(path: Path, hooks_dir: Path) -> str | None:
    """The refusal cause when ``path`` is a symlink (dangling or not) that
    resolves outside the hooks dir: a write would follow the link into a
    tracked in-tree script or a file shared by other repos (part E §Where it
    may install) — `_hooks_dir_ok` realpaths only the directory."""
    if not path.is_symlink():
        return None
    resolved = path.resolve()
    root = hooks_dir.resolve()
    if root in resolved.parents:
        return None
    return (f"{path.name} is a symlink to {resolved}, outside the git hooks dir "
            "(a tracked in-tree or shared hook — a block there would change "
            "every other clone or repo that uses it)")


def _target_for(hooks_dir: Path, name: str) -> tuple:
    """``(target, cause)``: the file the block goes in (part E §Install: the
    hook itself, or ``<hook>.legacy`` behind a pre-commit-framework script),
    and the refusal cause when the install must not touch it, else None."""
    hook = hooks_dir / name
    link_cause = _link_out_cause(hook, hooks_dir)
    if link_cause:
        return hook, link_cause
    if not hook.exists():
        return hook, None
    if not os.access(str(hook), os.X_OK):
        return hook, f"{name} is not executable (a disabled hook; chmod +x would re-enable its foreign lines)"
    if not _is_generated(_read(hook)):
        if _non_shell(hook):
            return hook, f"{name} shebang is not a POSIX shell (the block would never run)"
        return hook, None
    legacy = hooks_dir / (name + ".legacy")
    link_cause = _link_out_cause(legacy, hooks_dir)
    if link_cause:
        return legacy, link_cause
    if not _has_hook_dir(_read(hook)):
        return legacy, f"{name} pre-commit script has no --hook-dir (hook_impl never runs a legacy hook)"
    if legacy.exists() and not os.access(str(legacy), os.X_OK):
        return legacy, f"{name}.legacy is not executable (pre-commit skips it; chmod +x would re-enable it)"
    if legacy.exists() and _non_shell(legacy):
        return legacy, f"{name}.legacy shebang is not a POSIX shell (the block would never run)"
    return legacy, None


def install_hook(hooks_dir: Path, name: str) -> None:
    """Insert the current block into this one hook (or its `.legacy`).

    Refuses (Refused, carrying the two snippets) before anything is written;
    a current block is a no-op; an older or unversioned block is replaced in
    place, every foreign line kept."""
    target, cause = _target_for(hooks_dir, name)
    if cause:
        raise Refused(cause, snippets_for(cause))
    if not target.exists():
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text("#!/bin/sh\n" + "\n".join(block_lines(name)) + "\n",
                          encoding="utf-8")
        target.chmod(target.stat().st_mode | 0o111)
        return
    lines = _read(target).splitlines()
    lead = lines[:1] if lines and lines[0].startswith("#!") else []
    rest = lines[len(lead):]
    found = _find_sentinel(rest)
    if found is None:
        # Right after the shebang: a husky-style `exit` or an `exec`-terminated
        # hook never returns, so an appended block would never run; the block
        # exits only on a refusal, so the foreign lines still run after a pass.
        new_lines = lead + block_lines(name) + rest
    else:
        begin, end, version = found
        if version == BODY_VERSION:
            return  # current block: idempotent no-op
        new_lines = lead + rest[:begin] + block_lines(name) + rest[end + 1:]
    target.write_text("\n".join(new_lines) + "\n", encoding="utf-8")


def hook_status(hooks_dir: Path, name: str) -> dict:
    """The per-hook H dict (part E §status): target, manager, sentinel,
    version, stale, effective. The `sentinel` is reported from the target
    file whenever it exists (a disabled hook still holds it); `effective`
    additionally needs the hook and target executable, and — for a
    pre-commit script — the script to pass `--hook-dir` so `hook_impl` runs
    the `<hook>.legacy`."""
    hook = hooks_dir / name
    h = {"target": None, "manager": None, "sentinel": False,
         "version": None, "stale": False, "effective": False}
    if not hook.exists():
        return h
    text = _read(hook)
    hook_exec = os.access(str(hook), os.X_OK)
    if _is_generated(text):
        h["manager"] = "pre-commit"
        h["target"] = "legacy"
        target_path = hooks_dir / (name + ".legacy")
        runs = hook_exec and _has_hook_dir(text)
    else:
        h["manager"] = "foreign"
        h["target"] = "hook"
        target_path = hook
        runs = hook_exec and not _non_shell(hook)
    if target_path.exists():
        found = _find_sentinel(_read(target_path).splitlines())
        if found is not None:
            version = found[2]
            h["sentinel"] = True
            h["version"] = version
            h["stale"] = version is None or version < BODY_VERSION
    h["effective"] = bool(runs and h["sentinel"] and target_path.exists()
                          and os.access(str(target_path), os.X_OK))
    return h


def hook_refusal_cause(hooks_dir: Path) -> str | None:
    """The first per-hook cause that would refuse the install now, else None.
    (The scope cause — the hooks dir outside the common dir — is the
    caller's, which knows ``ok`` from ``_hooks_dir_ok``.)"""
    for name in HOOK_NAMES:
        cause = _target_for(hooks_dir, name)[1]
        if cause:
            return cause
    return None
